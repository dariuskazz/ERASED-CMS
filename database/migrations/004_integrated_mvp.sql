CREATE TABLE IF NOT EXISTS comments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, content_id INT UNSIGNED NOT NULL, author_name VARCHAR(190) NOT NULL,
 author_email VARCHAR(190) NOT NULL, body TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'pending',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(content_id), INDEX(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, content_id INT UNSIGNED NOT NULL, title VARCHAR(255) NOT NULL,
 body LONGTEXT NOT NULL, editor_id INT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(content_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS languages (
 code VARCHAR(12) PRIMARY KEY, name VARCHAR(100) NOT NULL, native_name VARCHAR(100) NOT NULL,
 is_default TINYINT(1) NOT NULL DEFAULT 0, is_active TINYINT(1) NOT NULL DEFAULT 1, is_rtl TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
